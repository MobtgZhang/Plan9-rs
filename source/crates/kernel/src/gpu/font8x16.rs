//! 8x16 bitmap font for the kernel text console.
//!
//! Covers ASCII 0x20 (space) through 0x7F (DEL) — 96 glyphs.
//! Source: the Linux kernel `font_8x16.c` (originally from
//!   pcis BIOS, in the public domain). This is a widely-used,
//!   clean bitmap font.

/// Number of glyphs in the font table.
pub const GLYPH_COUNT: usize = 96;
/// Glyph width in pixels.
pub const GLYPH_WIDTH: usize = 8;
/// Glyph height in pixels.
pub const GLYPH_HEIGHT: usize = 16;
/// Bytes per glyph row.
pub const BYTES_PER_ROW: usize = (GLYPH_WIDTH + 7) / 8;

/// Returns a pointer to the 16-byte bitmap for the ASCII character `c`.
/// Returns None for characters outside 0x20..0x7F.
pub fn glyph(c: u8) -> Option<&'static [u8; GLYPH_HEIGHT]> {
    if c < 0x20 || c > 0x7F {
        return None;
    }
    let idx = (c - 0x20) as usize;
    FONT.as_ref().get(idx)
}

/// Like `glyph()` but returns a raw pointer — useful for FFI.
pub fn glyph_ptr(c: u8) -> Option<*const u8> {
    if c < 0x20 || c > 0x7F {
        return None;
    }
    let idx = (c - 0x20) as usize;
    Some(&FONT[idx] as *const u8)
}

